import {test,expect} from '@playwright/test'
for(const width of [360,390,780,1440])test(`friendly bank schedule builder and combined settings at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.addInitScript(theme=>localStorage.setItem('finance-theme',theme),width===360||width===780?'light':'dark')
 let connection:any={interval_hours:0,daily_time:'12:00',schedule:null,state:'ready',version:1,last_error:'',debug_browser:0}
 const writes:any[]=[]
 await page.route('**/api/fnb**',async route=>{
  const request=route.request(),path=new URL(request.url()).pathname
  if(request.method()==='GET'){await route.fulfill({json:{connection,accounts:[]}});return}
  expect(path).toBe('/api/fnb/schedule')
  const body=request.postDataJSON();expect(body.version).toBe(connection.version);writes.push(body)
  connection={...connection,...body,version:connection.version+1}
  await route.fulfill({json:{ok:true}})
 })
 async function banking(){
  if(width<=390){await page.getByRole('navigation',{name:'Mobile navigation',exact:true}).getByRole('button',{name:'More',exact:true}).click();await page.getByRole('navigation',{name:'More pages',exact:true}).getByRole('button',{name:'Settings',exact:true}).click()}
  else await page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('button',{name:'Settings',exact:true}).click()
  await page.getByRole('tab',{name:'Accounts & banking',exact:true}).click()
 }
 await page.goto('/')
 await page.getByLabel('Username',{exact:true}).fill('demo');await page.getByLabel('Password',{exact:true}).fill('synthetic-browser-password')
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible()
 await banking()
 await expect(page.getByRole('tab',{name:'Accounts',exact:true})).toHaveCount(0)
 await expect(page.getByRole('tab',{name:'Banking',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Open Accounts',exact:true})).toBeVisible()
 const panel=page.locator('.banking-settings')
 await panel.locator('summary').filter({hasText:'Automatic refresh'}).click()
 const frequency=panel.getByLabel('Refresh schedule',{exact:true}),first=panel.getByLabel('Refresh time 1',{exact:true}),save=panel.getByRole('button',{name:'Save refresh schedule',exact:true})
 await expect(frequency).toHaveValue('daily');await expect(first).toHaveValue('12:00')
 await frequency.selectOption('weekly')
 await panel.getByRole('button',{name:'Weekends',exact:true}).click()
 await expect(panel.getByLabel('Saturday',{exact:true})).toBeChecked()
 await expect(panel.getByLabel('Sunday',{exact:true})).toBeChecked()
 await panel.getByLabel('Saturday',{exact:true}).uncheck();await panel.getByLabel('Sunday',{exact:true}).uncheck()
 await save.click();await expect(panel.getByLabel('Monday',{exact:true})).toBeFocused()
 await expect(panel.getByRole('alert').filter({hasText:'Choose at least one day.'})).toBeVisible();expect(writes).toHaveLength(0)
 await panel.getByLabel('Monday',{exact:true}).check();await panel.getByLabel('Wednesday',{exact:true}).check()
 await first.fill('07:00');await panel.getByRole('button',{name:'Add another time',exact:true}).click()
 const second=panel.getByLabel('Refresh time 2',{exact:true})
 await second.fill('07:00');await second.blur();await save.click()
 await expect(panel.getByText('Choose a different time.',{exact:true}).first()).toBeVisible();expect(writes).toHaveLength(0)
 await second.fill('18:00')
 await expect(panel.getByRole('status')).toContainText('Every Monday, Wednesday at 07:00 and 18:00 SAST')
 await save.click();await expect.poll(()=>writes.length).toBe(1)
 expect(writes[0].schedule).toEqual({frequency:'weekly',times:['07:00','18:00'],weekdays:[1,3]})
 // Switching settings tabs retains the schedule draft without retaining credential drafts.
 await second.fill('19:30')
 await page.getByRole('tab',{name:'General',exact:true}).click();await page.getByRole('tab',{name:'Accounts & banking',exact:true}).click()
 await expect(second).toHaveValue('19:30')
 await frequency.selectOption('monthly')
 const dates=panel.getByLabel('Dates of the month',{exact:true}),last=panel.getByRole('checkbox',{name:'Run on the last day of the month',exact:true})
 await dates.fill('32');await dates.blur()
 await expect(dates).toHaveAttribute('aria-invalid','true');await save.click();expect(writes).toHaveLength(1)
 await dates.fill('1, 15');await last.check()
 await panel.getByRole('button',{name:'Remove refresh time 2',exact:true}).click()
 await expect(panel.getByRole('status')).toContainText('Each month on 1, 15, the last day at 07:00 SAST')
 await dates.fill('');await expect(dates).not.toHaveAttribute('aria-invalid','true')
 await last.uncheck();await expect(dates).toHaveAttribute('aria-invalid','true')
 await last.check();await save.click();await expect.poll(()=>writes.length).toBe(2)
 expect(writes[1].schedule).toEqual({frequency:'monthly',times:['07:00'],month_days:[],last_day:true})
 await page.reload();await banking()
 await panel.locator('summary').filter({hasText:'Automatic refresh'}).click()
 await expect(frequency).toHaveValue('monthly');await expect(last).toBeChecked();await expect(dates).toHaveValue('')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 for(const control of [save,panel.getByRole('button',{name:'Add another time',exact:true})]) {
  const bounds=await control.boundingBox();expect(bounds!.height).toBeGreaterThanOrEqual(44)
 }
 await frequency.selectOption('interval')
 const hours=panel.getByLabel('Hours between refreshes',{exact:true})
 await hours.fill('0');await hours.blur();await save.click()
 await expect(hours).toHaveAttribute('aria-invalid','true');expect(writes).toHaveLength(2)
 await hours.fill('3');await save.click();await expect.poll(()=>writes.length).toBe(3)
 expect(writes[2].schedule).toBeNull();expect(writes[2].interval_hours).toBe(3)
 await expect(panel.locator('summary').filter({hasText:'Automatic refresh'})).toContainText('Every 3 hours')
 await frequency.selectOption('0');await save.click();await expect.poll(()=>writes.length).toBe(4)
 expect(writes[3].schedule).toBeNull();expect(writes[3].interval_hours).toBe(0)
 await page.getByRole('button',{name:'Open Accounts',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Accounts',exact:true})).toBeVisible()
})
