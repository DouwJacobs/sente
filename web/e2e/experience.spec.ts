import {test,expect,type Page} from '@playwright/test'
async function navigate(page:Page,name:string,width:number){
 if(width<=760&&!['Dashboard','Transactions','Review'].includes(name)){
  await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('button',{name:'More',exact:true}).click()
  await page.getByRole('navigation',{name:'More pages'}).getByRole('button',{name,exact:true}).click()
 }else await page.getByRole('navigation',{name:width<=760?'Mobile navigation':'Main navigation',exact:true}).getByRole('button',{name,exact:true}).click()
}
async function fits(page:Page){
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 for(const action of await page.locator('.empty-actions button:visible').all()){
  const box=await action.boundingBox();expect(box!.height).toBeGreaterThanOrEqual(44)
  expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.x+box!.width).toBeLessThanOrEqual(page.viewportSize()!.width+1)
 }
}
