test('dashboard failure offers recovery without showing a first-use state',async({page})=>{
 let fail=true
 await page.route('**/api/dashboard?**',async route=>{if(fail)await route.fulfill({status:503,json:{error:'Temporarily unavailable'}});else await route.continue()})
 await page.goto('/');await page.getByLabel('Username',{exact:true}).fill('demo');await page.getByLabel('Password',{exact:true}).fill('synthetic-browser-password')
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 const error=page.getByRole('region',{name:'Dashboard unavailable',exact:true});await expect(error).toBeVisible()
 await expect(page.getByRole('region',{name:'No spending yet'})).toHaveCount(0)
 fail=false;await error.getByRole('button',{name:'Retry dashboard',exact:true}).click()
 await expect(page.getByRole('region',{name:'Period totals',exact:true})).toBeVisible();await expect(error).toHaveCount(0)
})

test('pending actions keep their name and width and prevent repeated submissions',async({page})=>{
 let release!:()=>void
 const held=new Promise<void>(resolve=>{release=resolve})
 await page.route('**/api/login',async route=>{await held;await route.continue()})
 await page.goto('/');await page.getByLabel('Username',{exact:true}).fill('demo');await page.getByLabel('Password',{exact:true}).fill('synthetic-browser-password')
 const button=page.getByRole('button',{name:/^Sign(ing)? in$/}),before=await button.boundingBox()
 await button.click();await expect(button).toHaveAttribute('aria-busy','true');await expect(button).toBeDisabled()
 const after=await button.boundingBox();expect(after!.width).toBeCloseTo(before!.width,1);expect(after!.height).toBeCloseTo(before!.height,1)
 release();await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible()
})
